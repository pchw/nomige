function minesweeper(config: Config): RuleDoc {
  const mines = config.mines === "few" || config.mines === "many" ? config.mines : "normal";
  const label = { few: "少なめ", normal: "ふつう", many: "多め" }[mines];
  return {
    goal: "マス目のどこかに地雷が隠れている。順番に1マスずつ開けていき、地雷を踏んだ人の負け。",
    sections: [
      {
        title: "流れ",
        steps: [
          "最初の人はランダム、あとは席順。",
          "自分の番に、まだ開いていないマスを1つ選んで開ける。",
          "安全なマスなら、まわり8マスにある地雷の数が出る。次の人の番。",
          "地雷を開けたら、その人の負け。",
        ],
      },
      {
        title: "数字の読み方",
        items: [
          "数字は、そのマスのまわり8マス（縦・横・斜め）にある地雷の数。",
          "「・」（0）のまわりには地雷がない。そのまわりは安全に開けられる。",
          "1マス目は必ず安全。",
        ],
      },
      {
        title: `盤と地雷（今の設定：${label}）`,
        table: {
          head: ["人数", "盤", "地雷"],
          rows: [
            ["2〜5人", 3],
            ["6〜10人", 6],
          ].map(([people, count]) => {
            const b = boardSize(count as number, mines);
            return [people as string, `${b.cols}×${b.rows}`, `${b.mineCount}個`];
          }),
        },
      },
      {
        title: "安全なマスがなくなったら",
        items: [
          "開いていないマスが全部地雷になったら、次の人はどこを開けても地雷。",
          "安全なマスを残り何個か画面に出しているので、終盤は数えて逃げ切ろう。",
        ],
      },
      {
        title: "例",
        example: [
          "「1」のまわりに開いていないマスが1つだけ → そこは地雷確定。",
          "「・」のとなり → 安全確定。先に開けた者勝ち。",
        ],
      },
      {
        title: "みんなで見る",
        items: [
          "隠し情報はない。全員で盤を見て「そこはやばい！」と口を出してOK（決めるのは手番の人）。",
          "マスをタップすると黄色くなる。「このマスを開ける」か、もう一度タップで開ける。",
        ],
      },
    ],
  };
}

