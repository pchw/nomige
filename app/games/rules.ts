/** 詳しいルール（画面表示用）。設定によって内容が変わる部分は config から組み立てる */
export interface RuleSection {
  title: string;
  /** 箇条書き */
  items?: string[];
  /** 番号付きの手順 */
  steps?: string[];
  table?: { head: string[]; rows: string[][] };
  /** 具体例（囲みで表示） */
  example?: string[];
}

export interface RuleDoc {
  /** ねらい（1〜2文） */
  goal: string;
  sections: RuleSection[];
}

type Config = Record<string, unknown>;

function hundredOne(config: Config): RuleDoc {
  const limit = config.limit === 51 ? 51 : 101;
  const cards: string[][] = [
    ["1〜10", "各4枚", "その数を足す"],
    ...(limit === 101 ? [["+20", "4枚", "20 を足す"]] : []),
    ["±10", "4枚", "出すときに +10 か −10 を選ぶ（0 より下にはならない）"],
    ["リターン ⇄", "3枚", "合計はそのまま。順番が逆回りになる"],
    ["パス", "3枚", "合計はそのまま"],
    [`${limit}`, "2枚", `合計を ちょうど ${limit} にする`],
  ];
  return {
    goal: `手札を1枚ずつ出して場の合計を増やしていく。合計が ${limit} を超えるカードを出してしまった人の負け。`,
    sections: [
      {
        title: "準備",
        items: [
          "各自に手札が3枚配られる（自分にだけ見える）。",
          "場の合計は 0 からスタート。最初の人はランダム、あとは席順。",
        ],
      },
      {
        title: "流れ",
        steps: [
          "自分の番になったら、手札から1枚出す。",
          "出したカードの分だけ場の合計が変わる。",
          "山札から1枚引いて、手札は3枚に戻る。",
          "次の人の番（リターンが出たら逆回り）。",
        ],
      },
      { title: "カード", table: { head: ["カード", "枚数", "効果"], rows: cards } },
      {
        title: "負け",
        items: [
          `出したカードで合計が ${limit} を超えた人の負け。ちょうど ${limit} はセーフ。`,
          `どのカードを出しても超えてしまうときも、1枚は出さないといけない（覚悟を決めて！）。`,
          `合計が ${limit} のときに出して助かるのは、パス・リターン・−10・${limit} だけ。`,
        ],
      },
      {
        title: "例",
        example: [
          `合計 ${limit - 6} で手札が [7] [パス] [3] のとき`,
          `→ 7 を出すと ${limit + 1} でアウト。3 なら ${limit - 3}、パスなら ${limit - 6} のまま。`,
        ],
      },
      {
        title: "画面の操作",
        items: [
          "カードをタップするとすぐ出る。±10 だけは +10 / −10 を選ぶ。",
          "赤い斜線のカードは「出すとアウト」の印。",
          "山札がなくなったら、出たカードを混ぜて山札に戻す（自動）。",
        ],
      },
    ],
  };
}

