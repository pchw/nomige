import type { GameId } from "./types";

/** 詳しいルール（画面表示用）。設定によって内容が変わる部分は config から組み立てる */
export interface RuleSection {
  title: string;
  /** 箇条書き */
  items?: string[];
  /** 番号付きの手順 */
  steps?: string[];
  table?: { head: string[]; rows: string[][] };
  /** 具体例（囲みで表示） */
  example?: string[];
}

export interface RuleDoc {
  /** ねらい（1〜2文） */
  goal: string;
  sections: RuleSection[];
}

type Config = Record<string, unknown>;

function hundredOne(config: Config): RuleDoc {
  const limit = config.limit === 51 ? 51 : 101;
  const cards: string[][] = [
    ["1〜10", "各4枚", "その数を足す"],
    ...(limit === 101 ? [["+20", "4枚", "20 を足す"]] : []),
    ["±10", "4枚", "出すときに +10 か −10 を選ぶ（0 より下にはならない）"],
    ["リターン ⇄", "3枚", "合計はそのまま。順番が逆回りになる"],
    ["パス", "3枚", "合計はそのまま"],
    [`${limit}`, "2枚", `合計を ちょうど ${limit} にする`],
  ];
  return {
    goal: `手札を1枚ずつ出して場の合計を増やしていく。合計が ${limit} を超えるカードを出してしまった人の負け。`,
    sections: [
      {
        title: "準備",
        items: [
          "各自に手札が3枚配られる（自分にだけ見える）。",
          "場の合計は 0 からスタート。最初の人はランダム、あとは席順。",
        ],
      },
      {
        title: "流れ",
        steps: [
          "自分の番になったら、手札から1枚出す。",
          "出したカードの分だけ場の合計が変わる。",
          "山札から1枚引いて、手札は3枚に戻る。",
          "次の人の番（リターンが出たら逆回り）。",
        ],
      },
      { title: "カード", table: { head: ["カード", "枚数", "効果"], rows: cards } },
      {
        title: "負け",
        items: [
          `出したカードで合計が ${limit} を超えた人の負け。ちょうど ${limit} はセーフ。`,
          `どのカードを出しても超えてしまうときも、1枚は出さないといけない（覚悟を決めて！）。`,
          `合計が ${limit} のときに出して助かるのは、パス・リターン・−10・${limit} だけ。`,
        ],
      },
      {
        title: "例",
        example: [
          `合計 ${limit - 6} で手札が [7] [パス] [3] のとき`,
          `→ 7 を出すと ${limit + 1} でアウト。3 なら ${limit - 3}、パスなら ${limit - 6} のまま。`,
        ],
      },
      {
        title: "画面の操作",
        items: [
          "カードをタップするとすぐ出る。±10 だけは +10 / −10 を選ぶ。",
          "赤い斜線のカードは「出すとアウト」の印。",
          "山札がなくなったら、出たカードを混ぜて山札に戻す（自動）。",
        ],
      },
    ],
  };
}

function liarsDice(config: Config): RuleDoc {
  const wild = config.onesWild !== false;
  const dice =
    config.dicePerPlayer === "auto" || config.dicePerPlayer === undefined
      ? "3〜5人なら5個、6〜8人なら3個"
      : `${config.dicePerPlayer}個`;
  return {
    goal: "全員のサイコロを合わせて「〇の目が△個以上ある」と宣言を吊り上げていく。嘘だと思ったら「ダウト！」。外した方の負け。",
    sections: [
      {
        title: "準備",
        items: [
          `各自のサイコロ（1人${dice}）をアプリが振る。自分の目だけが見える。`,
          "最初の人はランダム、あとは席順。",
        ],
      },
      {
        title: "流れ",
        steps: [
          "最初の人が「〇の目が△個以上ある」と宣言する（全員のサイコロの合計で考える）。",
          "次の人は、前より強い宣言をするか、「ダウト！」と言う。",
          "ダウトが出たら全員のサイコロを公開して数える。",
        ],
      },
      {
        title: "「前より強い宣言」とは",
        items: ["個数を増やす（目は何でもよい）", "または、個数は同じで、より大きい目にする"],
        table: {
          head: ["前の宣言「4の目が3個」のあと", "OK / NG"],
          rows: [
            ["5の目が3個", "OK（同じ個数で大きい目）"],
            ["2の目が4個", "OK（個数を増やした）"],
            ["3の目が3個", "NG（目が小さい）"],
            ["6の目が2個", "NG（個数が減った）"],
          ],
        },
      },
      {
        title: wild ? "1の目はワイルド（今の設定：ON）" : "1の目はワイルド（今の設定：OFF）",
        items: wild
          ? [
              "1の目は、どの目としても数える（「5の目が△個」なら 5 と 1 を合わせて数える）。",
              "1の目そのものは宣言できない。",
            ]
          : ["1の目は1としてだけ数える。1の目も宣言できる。"],
      },
      {
        title: "負け",
        items: [
          "実際の個数が宣言以上 → 宣言は本当だった。ダウトした人の負け。",
          "実際の個数が宣言より少ない → 宣言は嘘だった。宣言した人の負け。",
          "ダウトは1回で決着（1ラウンド終了）。",
        ],
      },
      {
        title: "例",
        example: [
          "4人 × 5個 = 全部で20個。Aさん「5の目が6個以上」→ Bさん「ダウト！」",
          wild
            ? "公開すると 5 が4個、1 が3個 → ワイルド込みで7個。宣言は本当なので Bさんの負け。"
            : "公開すると 5 が4個 → 6個に足りないので宣言は嘘。Aさんの負け。",
        ],
      },
      {
        title: "コツ",
        items: [
          wild
            ? "他の人のサイコロは、1個あたり約 1/3 の確率で狙いの目（か1）になる。"
            : "他の人のサイコロは、1個あたり約 1/6 の確率で狙いの目になる。",
          "自分の目の数 + 他の人のサイコロ数 × その確率 が「ありそうな個数」の目安。",
        ],
      },
      {
        title: "画面の操作",
        items: [
          "個数を −/＋、目をタップで選んで「宣言」。最初は「最小の吊り上げ」が入っているので、そのまま押せば1タップ。",
          "前より弱い組み合わせのときは宣言ボタンが押せない。",
        ],
      },
    ],
  };
}

function highLow(config: Config): RuleDoc {
  const rideTheBus = config.stages !== "highLowOnly";
  return {
    goal: "次にめくるトランプを全員で同時に予想する。当てた人から「降車」してセーフ。最後までバスに残った1人の負け。",
    sections: [
      {
        title: "流れ",
        steps: [
          "ステージごとに質問が出る（下の表）。",
          "バスに残っている全員が、同時にこっそり予想する。",
          "全員の予想がそろったらカードをめくる。",
          "当たった人はバスを降りてセーフ。外れた人は次のステージへ。",
        ],
      },
      rideTheBus
        ? {
            title: "ステージ（今の設定：ライド・ザ・バス）",
            table: {
              head: ["ステージ", "質問"],
              rows: [
                ["1", "赤か黒か？"],
                ["2", "1枚目より上か下か？"],
                ["3", "1枚目と2枚目の間か外か？"],
                ["4", "マークは？（♠♥♦♣）"],
                ["5〜", "直前のカードより上か下か？"],
                ["15〜", "マークは？（長引いたとき用）"],
              ],
            },
          }
        : {
            title: "ステージ（今の設定：上か下かのみ）",
            items: [
              "最初に基準のカードを1枚めくる。",
              "以降は毎回「直前のカードより上か下か？」。15ステージ目からはマーク当て。",
            ],
          },
      {
        title: "細かいルール",
        items: [
          "数字の強さは A=1、J=11、Q=12、K=13。",
          "同じ数字が出たら（「間か外か」で境界と同じ数字も）全員ハズレ。",
          "残っている全員が当たった／全員が外れたときは、誰も降りずに次のステージへ。",
          "降りた人は観戦。",
        ],
      },
      {
        title: "例",
        example: [
          "1枚目 ♥8、2枚目 ♠3 → ステージ3は「3と8の間か外か」",
          "→ 5 なら「間」が正解、10 なら「外」が正解。3 や 8 なら全員ハズレ。",
        ],
      },
      {
        title: "画面の操作",
        items: ["ボタンで予想。全員がそろうまでは変更できる。"],
      },
    ],
  };
}

function kabuttaraOut(config: Config): RuleDoc {
  const spoilers = config.spoilers !== false;
  const stray = config.strayAnimal !== false;
  return {
    goal: "全員が同時に動物を1匹選ぶ。誰とも被らなかった人から抜けていき、最後まで残った1人の負け。",
    sections: [
      {
        title: "流れ",
        steps: [
          "全員が同時にこっそり動物を1匹選ぶ。",
          "全員がそろったら一斉に公開。",
          "残っている人のうち、誰とも被らなかった人はセーフで抜ける。",
          "被った人は残って、もう一度。",
        ],
      },
      {
        title: "被りとは",
        items: [
          "同じ動物を選んだ人が他にもいたら「被り」。",
          ...(spoilers ? ["おじゃま役（抜けた人）と同じ動物でも被り。"] : []),
          ...(stray ? ["のら動物（アプリがこっそり選ぶ1匹）と同じでも被り。"] : []),
        ],
      },
      {
        title: spoilers ? "おじゃま役（今の設定：ON）" : "おじゃま役（今の設定：OFF）",
        items: spoilers
          ? [
              "抜けた人も毎回動物を選ぶ。残っている人と同じ動物を選べば、その人を被らせられる。",
              "おじゃま役自身は負けない。選びたくないときは「今回はおじゃましない」を押す。",
            ]
          : ["抜けた人は観戦するだけ。"],
      },
      {
        title: stray ? "のら動物（今の設定：ON）" : "のら動物（今の設定：OFF）",
        items: stray
          ? ["毎回アプリも1匹こっそり選ぶ。公開まで何を選んだかは分からない。"]
          : ["アプリは動物を選ばない。"],
      },
      {
        title: "決着がつかないとき",
        items: [
          "残っている全員が被らなかったら、誰も抜けずにやり直し。",
          "10回やっても決まらなければ、残っている人からルーレットで1人。",
          ...(!spoilers && !stray
            ? ["おじゃま役・のら動物がどちらも OFF のときは、残り2人になった時点でルーレット。"]
            : []),
        ],
      },
      {
        title: "例",
        example: [
          `残り3人：Aさん🐱 Bさん🐱 Cさん🐶${spoilers ? " ／ おじゃまDさん🐰" : ""}${stray ? " ／ のら🦊" : ""}`,
          "→ Cさんだけ被らずに抜ける。AさんとBさんで次の回へ。",
        ],
      },
      {
        title: "話してもいい",
        items: ["選んでいる間に「ネコにする」と宣言するのは自由（嘘でもOK）。"],
      },
    ],
  };
}

function wolfAndPigs(config: Config): RuleDoc {
  const wolfLosesOnRunoffMiss = config.runoffMiss !== "retry";
  return {
    goal: "わら・木・レンガの家から1つを選んで隠れる。狼が選んだ家にいたら負け。狼が誰なのかは分からない。",
    sections: [
      {
        title: "配役",
        items: [
          "1人だけがこっそり「狼」、残りは「子豚」になる。",
          "自分の役は「長押しで役を確認」で見る。確認したら「確認した」を押す。",
        ],
      },
      {
        title: "流れ",
        steps: [
          "全員が同時にこっそり家を選ぶ。子豚は隠れる家、狼は襲う家。",
          "全員がそろったら一斉に公開。",
          "狼が襲った家の中で結果が決まる（下の表）。",
        ],
      },
      {
        title: "結果",
        table: {
          head: ["狼が襲った家に", "どうなる"],
          rows: [
            ["子豚が1匹", "その子豚の負け"],
            ["子豚が2匹以上", "その子豚たちで延長戦"],
            ["誰もいない", "狼の負け"],
          ],
        },
      },
      {
        title: "延長戦",
        items: [
          "捕まった子豚たちと狼（同じ人）だけで、もう一度家を選ぶ。",
          "対象外の人は観戦。「見ています」を押す（狼だけが操作していると目立たないように）。",
          wolfLosesOnRunoffMiss
            ? "延長戦で狼が空き家を襲ったら、狼の負け（今の設定）。"
            : "延長戦で狼が空き家を襲ったら、やり直し（今の設定）。",
        ],
      },
      {
        title: "狼の正体",
        items: [
          "負けが決まるまで狼が誰かは明かされない。公開されるのは「どの家が襲われたか」だけ。",
          "誰が選び終わったかも表示しない（人数だけ）。",
        ],
      },
      {
        title: "話し合い",
        items: [
          "選んでいる間は自由に話してOK。「レンガに行くわ」は本当でも嘘でもいい。",
          "狼は、子豚を1つの家に集めるように誘導すると有利。",
          "家はわら・木・レンガで見た目が違うだけ。ルール上の違いはない。",
        ],
      },
      {
        title: "例",
        example: [
          "子豚 A・B・C・D、狼 E。A・B → わら、C → 木、D → レンガ。",
          "E がわらを襲う → A と B で延長戦。E が木を襲う → C の負け。",
        ],
      },
    ],
  };
}

const BUILDERS: Record<GameId, (config: Config) => RuleDoc> = {
  "hundred-one": hundredOne,
  "liars-dice": liarsDice,
  "high-low": highLow,
  "kabuttara-out": kabuttaraOut,
  "wolf-and-pigs": wolfAndPigs,
};

export function rulesFor(gameId: GameId, config: Config): RuleDoc {
  return BUILDERS[gameId](config);
}

